// Read-only ECC installation integrity check. No model, network, DB, or hook calls.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

const projectRoot = fileURLToPath(new URL('../../', import.meta.url));
const record = JSON.parse(fs.readFileSync(path.join(projectRoot, 'docs/ecc-installation.json'), 'utf8'));
const failures = [];
function check(ok, label) {
  if (!ok) failures.push(label);
  console.log(`${ok ? 'OK' : 'FAIL'}: ${label}`);
}
function files(root, suffix) {
  return fs.readdirSync(root, { recursive: true, withFileTypes: true })
    .filter(entry => entry.isFile() && entry.name.endsWith(suffix))
    .map(entry => path.join(entry.parentPath ?? entry.path, entry.name));
}
function digest(file) {
  return createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}
// This deliberately reads only simple generated TOML fields, not arbitrary TOML.
// Use native Codex doctor / config-read diagnostics for complete schema validation.
function stringField(text, key) {
  const value = text.split(/\r?\n/).find(line => line.startsWith(`${key} = `));
  return value ? JSON.parse(value.slice(key.length + 3)) : undefined;
}
function hasDisabledTable(text, heading) {
  const start = text.indexOf(heading);
  if (start < 0) return false;
  const body = text.slice(start + heading.length).split(/\n\s*\[/, 1)[0];
  return /^enabled\s*=\s*false\s*$/m.test(body);
}

try {
  const commit = execFileSync('git', ['rev-parse', 'HEAD'], {
    cwd: record.sourceRoot, encoding: 'utf8', windowsHide: true,
  }).trim();
  check(commit === record.commit, 'Pinned source commit');
  const status = execFileSync('git', ['status', '--porcelain'], {
    cwd: record.sourceRoot, encoding: 'utf8', windowsHide: true,
  }).trim();
  check(status === '', 'Unmodified upstream checkout');
  const manifestFile = '.codex-plugin/plugin.json';
  const pluginManifest = JSON.parse(fs.readFileSync(path.join(record.pluginRoot, manifestFile), 'utf8'));
  check(pluginManifest.name === 'ecc' && pluginManifest.version === record.version, 'Native plugin version');
  check(digest(path.join(record.sourceRoot, manifestFile)) === digest(path.join(record.pluginRoot, manifestFile)), 'Manifest matches reviewed source');

  const sourceSkills = files(path.join(record.sourceRoot, 'skills'), 'SKILL.md');
  const cachedSkills = files(path.join(record.pluginRoot, 'skills'), 'SKILL.md');
  check(sourceSkills.length === record.expectedSkills && cachedSkills.length === record.expectedSkills, `${record.expectedSkills} skill files in source and plugin`);
  const sameSkills = sourceSkills.every(file => {
    const cached = path.join(record.pluginRoot, path.relative(record.sourceRoot, file));
    return fs.existsSync(cached) && digest(file) === digest(cached);
  });
  check(sameSkills, 'Every cached SKILL.md matches source');
  const migratedSkills = files(path.join(record.pluginRoot, '.codex-plugin/migrated-command-skills'), 'SKILL.md');
  check(migratedSkills.length === record.expectedMigratedCommandSkills, '35 command skills generated by native installer');
  const sourceAgents = files(path.join(record.sourceRoot, 'agents'), '.md');
  check(sourceAgents.length === record.expectedSourceAgents, `${record.expectedSourceAgents} source agent instructions`);
  check(files(path.join(record.sourceRoot, 'commands'), '.md').length === record.expectedCommands, `${record.expectedCommands} legacy command references`);

  const adapterFailures = [];
  for (const name of record.adapterNames) {
    try {
      const text = fs.readFileSync(path.join(record.codexRoot, 'agents', `${name}.toml`), 'utf8');
      const source = `${record.sourceRoot}/agents/${name.slice(4)}.md`;
      if (stringField(text, 'name') !== name || !stringField(text, 'description') ||
          !stringField(text, 'developer_instructions')?.includes(source) ||
          /^model\s*=/m.test(text) || !fs.existsSync(source)) adapterFailures.push(name);
    } catch { adapterFailures.push(name); }
  }
  check(record.adapterNames.length === 68 && adapterFailures.length === 0, '68 nonempty adapters, valid source references, inherited model');
  if (adapterFailures.length) console.log(`Adapter failures: ${adapterFailures.join(', ')}`);

  const config = fs.readFileSync(path.join(record.codexRoot, 'config.toml'), 'utf8');
  check(hasDisabledTable(config, '[plugins."ecc@ecc".mcp_servers."chrome-devtools"]'), 'Duplicate Chrome MCP disabled');
  check(hasDisabledTable(config, `[hooks.state."${record.hookKey}"]`), 'ECC SessionStart hook explicitly disabled');
  check(fs.existsSync(record.configBackup), 'Original config backup retained');
  console.log('Native role/skill discovery requires a separate Codex diagnostic; this script does not invoke an agent.');
} catch (error) {
  failures.push('Read-only integrity check could not complete');
  console.error(error.message);
}
process.exitCode = failures.length ? 1 : 0;
